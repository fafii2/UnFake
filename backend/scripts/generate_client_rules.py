"""Generate JS regex constants from backend rules so both gates use one vocabulary."""
import json
from pathlib import Path
from services import triage, preprocessor


def generate():
    patterns = {key: value.pattern for key, value in vars(triage).items() if key.endswith('_PATTERN')}
    patterns['BROADCAST_PREFIXES_REGEX'] = preprocessor.BROADCAST_PREFIXES_REGEX.pattern
    target = Path(__file__).resolve().parents[2] / 'extension' / 'shared' / 'rules.js'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text('// Generated by python -m scripts.generate_client_rules. Do not edit.\n' +
                      'globalThis.UnFakeRules = ' + json.dumps(patterns, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')


if __name__ == '__main__':
    generate()
